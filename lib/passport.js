// #1048: subscription passport - a shareable report of what is connected.
// Everything here is pure rendering; masking happens before the rows arrive and
// the renderer never sees a token.
const HTML_ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }

export function escapeHtml(value) {
  return String(value == null ? '' : value).replace(/[&<>"']/g, (ch) => HTML_ESCAPES[ch])
}

/** @param {any} input */
export function normalizeReportRow(input = {}) {
  const rawUsage = input.usagePercent
  const hasUsage = rawUsage !== null && rawUsage !== undefined && rawUsage !== '' && Number.isFinite(Number(rawUsage))
  return {
    provider: String(input.provider || ''),
    label: String(input.label || ''),
    ref: String(input.ref || ''),
    connected: Boolean(input.connected),
    usagePercent: hasUsage ? Math.max(0, Math.min(100, Number(rawUsage))) : null,
    resetAt: Number(input.resetAt) || 0,
    cooldownUntil: Number(input.cooldownUntil) || 0,
    monthlyCost: Number(input.monthlyCost) || 0,
  }
}

/** @param {{ rows?: any[], generatedAt?: number, version?: string, privacy?: boolean }} input */
export function buildPassport(input = {}) {
  const rows = (Array.isArray(input.rows) ? input.rows : []).map(normalizeReportRow).filter((row) => row.provider)
  const connected = rows.filter((row) => row.connected)
  return {
    generatedAt: Number(input.generatedAt) || Date.now(),
    version: String(input.version || ''),
    privacy: Boolean(input.privacy),
    rows,
    totals: {
      accounts: rows.length,
      connected: connected.length,
      monthlyCost: rows.reduce((sum, row) => sum + row.monthlyCost, 0),
    },
  }
}

/** @param {any} report */
export function renderPassportMarkdown(report) {
  const data = buildPassport(report)
  const when = new Date(data.generatedAt).toISOString().replace('T', ' ').slice(0, 16) + ' UTC'
  const lines = [
    '# Subscriptions passport',
    '',
    `Generated: ${when}${data.version ? ` · plugin ${data.version}` : ''}${data.privacy ? ' · privacy mask on' : ''}`,
    '',
    `Accounts: ${data.totals.connected}/${data.totals.accounts} connected · monthly cost ${data.totals.monthlyCost.toFixed(2)}`,
    '',
    '| Provider | Label | Ref | Status | Quota |',
    '|---|---|---|---|---|',
  ]
  for (const row of data.rows) {
    const quota = row.usagePercent == null ? 'n/a' : `${Math.round(row.usagePercent)}% used`
    const status = row.cooldownUntil > Date.now() ? 'cooldown' : row.connected ? 'connected' : 'not connected'
    lines.push(`| ${cell(row.provider)} | ${cell(row.label)} | ${cell(row.ref)} | ${status} | ${quota} |`)
  }
  if (!data.rows.length) lines.push('| - | no accounts configured | - | - | - |')
  lines.push('', '_No tokens, emails or proxy URLs are included. Generated by dsh-subscriptions._', '')
  return lines.join('\n')
}

function cell(value) {
  return String(value == null ? '' : value).replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

/** @param {any} report */
export function renderPassportHtml(report) {
  const data = buildPassport(report)
  const when = new Date(data.generatedAt).toISOString().replace('T', ' ').slice(0, 16) + ' UTC'
  const rows = data.rows.map((row) => {
    const quota = row.usagePercent == null ? 'n/a' : `${Math.round(row.usagePercent)}%`
    const status = row.cooldownUntil > Date.now() ? 'cooldown' : row.connected ? 'connected' : 'off'
    return `<tr><td>${escapeHtml(row.provider)}</td><td>${escapeHtml(row.label)}</td><td><code>${escapeHtml(row.ref)}</code></td><td class="s-${status.replace(/\s+/g, '-')}">${escapeHtml(status)}</td><td>${escapeHtml(quota)}</td></tr>`
  }).join('')
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Subscriptions passport</title>
<style>
body{font:14px/1.5 -apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;margin:0;padding:24px;background:#0d1117;color:#c9d1d9}
h1{font-size:18px;margin:0 0 4px}.meta{color:#8b949e;font-size:12px;margin-bottom:16px}
table{border-collapse:collapse;width:100%;max-width:900px}th,td{text-align:left;padding:8px 10px;border-bottom:1px solid #30363d;font-size:13px}
th{color:#8b949e;font-weight:600}.s-connected{color:#3fb950}.s-cooldown{color:#d29922}.s-off{color:#8b949e}
code{font-size:12px;color:#79c0ff}footer{margin-top:16px;color:#8b949e;font-size:12px}
</style></head>
<body>
<h1>Subscriptions passport</h1>
<div class="meta">${escapeHtml(when)}${data.version ? ` · plugin ${escapeHtml(data.version)}` : ''}${data.privacy ? ' · privacy mask on' : ''}<br>
${data.totals.connected}/${data.totals.accounts} connected · monthly cost ${escapeHtml(String(data.totals.monthlyCost.toFixed(2)))}</div>
<table><thead><tr><th>Provider</th><th>Label</th><th>Ref</th><th>Status</th><th>Quota</th></tr></thead>
<tbody>${rows || '<tr><td colspan="5">No accounts configured</td></tr>'}</tbody></table>
<footer>No tokens, emails or proxy URLs are included. Generated by dsh-subscriptions.</footer>
</body></html>`
}
